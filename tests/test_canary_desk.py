def test_the_config_is_the_sim_file_with_only_the_named_overrides(tmp_path: Path) -> None:
    raw = desk.build_config(tmp_path / "state")
    sim = yaml.safe_load(desk.SIM_CONFIG.read_text())
    state = (tmp_path / "state").resolve()

    assert raw["daemon"]["state_dir"] == str(state)
    assert raw["daemon"]["control_token_env"] == desk.TOKEN_ENV
    # Every explicit runtime path the sim file names is dropped, so S03 re-roots it.
    assert not set(DAEMON_STATE_LAYOUT) & set(raw["daemon"])
    assert raw["collection"]["storage_path"] == str(state / "sessions")
    assert raw["collection"]["replay_session"] is None
    assert raw["dashboard"]["host"] == "127.0.0.1"
    assert raw["dashboard"]["port"] == desk.DEFAULT_PORT
    assert raw["models"]["isolation_forest"]["enabled"] is False
    assert raw["models"]["lstm_autoencoder"]["enabled"] is False
    assert raw["collection"]["obd_source"] == "disabled"
    assert raw["hardware"]["can"]["interface"] == "virtual"

    # Nothing else differs from the sim file.
    for section, values in sim.items():
        for key, value in values.items():
            if (section, key) in {("daemon", name) for name in DAEMON_STATE_LAYOUT} | {
                ("collection", "storage_path"),
                ("collection", "replay_session"),
                ("dashboard", "host"),
            }:
                continue
            assert raw[section][key] == value, (section, key)



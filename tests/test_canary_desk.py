class FakeDaemon:
    """Stands in for the daemon child: alive until terminated or killed."""

    pid = 424242

    def __init__(self, *, wait_interrupts: int = 0) -> None:
        self.returncode: int | None = None
        self.terminated = False
        self.killed = False
        self.wait_interrupts = wait_interrupts

    def poll(self) -> int | None:
        return self.returncode

    def terminate(self) -> None:
        self.terminated = True
        self.returncode = -15

    def kill(self) -> None:
        self.killed = True
        self.returncode = -9

    def wait(self, timeout: float | None = None) -> int | None:
        if self.wait_interrupts and not self.killed:
            self.wait_interrupts -= 1
            raise KeyboardInterrupt
        return self.returncode



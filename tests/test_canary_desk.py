class Ran:
    def __init__(self, code: int = 0) -> None:
        self.calls: list[list[str]] = []
        self.code = code

    def __call__(self, argv: list[str], **_: Any) -> Any:
        self.calls.append(argv)
        return subprocess.CompletedProcess(argv, self.code)


def test_the_build_installs_only_when_node_modules_is_missing(tmp_path: Path) -> None:
    static = make_static(tmp_path, built=False)
    run = Ran()
    assert desk.ensure_dashboard(static, which=lambda _: "/bin/pnpm", run=run) == "dist/ missing"
    assert run.calls == [["/bin/pnpm", "install", "--frozen-lockfile"], ["/bin/pnpm", "build"]]

    (static / "node_modules").mkdir()
    run = Ran()
    desk.ensure_dashboard(static, which=lambda _: "/bin/pnpm", run=run)
    assert run.calls == [["/bin/pnpm", "build"]]



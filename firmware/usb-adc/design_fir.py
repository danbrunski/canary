"""Design the USB ADC firmware's decimation filter and write ``fir_taps.h``.

Run from the repo root (needs scipy, which the dev venv has)::

    .venv/bin/python firmware/usb-adc/design_fir.py          # rewrite the header
    .venv/bin/python firmware/usb-adc/design_fir.py --check  # fail if it is stale

The chain, all fixed by the ADC's own clock (64 MHz / 6, 239.5 + 12.5 cycles
per conversion):

1. the ADC converts CH0 continuously at FS_ADC = 42,328 Hz (DMA, no gaps);
2. stage 1 sums R1 = 21 conversions: a boxcar, decimated to 2,015.6 Hz;
3. stage 2 is a NUM_TAPS linear-phase FIR on that, decimated by R2 = 4 to
   503.9 Hz, the output rate.

The FIR passes 0..PASS_HZ flat and stops from STOP_HZ = FS_OUT - PROTECT_HZ:
anything above that would alias into 0..PROTECT_HZ, the band the output is
meant to resolve (the rail's injector pulsation, engine-order harmonics of
rpm/40 Hz: ~165 Hz near redline). The 100 nF divider capacitor (corner
~243 Hz) and the stage-1 boxcar guard the stage-1 aliases.

Taps are Q15 integers summing to exactly 32768, so DC passes with unit gain
and the output stays in 12-bit ADC counts.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from scipy import signal  # type: ignore[import-untyped]

ADC_CLOCK_HZ = 64_000_000 / 6
CYCLES_PER_CONVERSION = 239.5 + 12.5
FS_ADC = ADC_CLOCK_HZ / CYCLES_PER_CONVERSION
R1 = 21
R2 = 4
FS_STAGE1 = FS_ADC / R1
FS_OUT = FS_STAGE1 / R2
NUM_TAPS = 64
PASS_HZ = 180.0
PROTECT_HZ = 200.0
STOP_HZ = FS_OUT - PROTECT_HZ
Q = 15

HEADER = Path(__file__).with_name("fir_taps.h")


def design() -> np.ndarray:
    """Q15 integer taps, symmetric, summing to 2**Q."""
    taps = signal.remez(
        NUM_TAPS, [0, PASS_HZ, STOP_HZ, FS_STAGE1 / 2], [1, 0], weight=[1, 10], fs=FS_STAGE1
    )
    scaled: np.ndarray = np.round(taps / taps.sum() * (1 << Q)).astype(np.int64)
    # Put the rounding residue on the centre pair so the sum is exact and the
    # taps stay symmetric (linear phase).
    residue = (1 << Q) - int(scaled.sum())
    if residue % 2:
        raise SystemExit(f"odd rounding residue {residue}: pick another NUM_TAPS")
    mid = NUM_TAPS // 2
    scaled[mid - 1] += residue // 2
    scaled[mid] += residue // 2
    assert int(scaled.sum()) == 1 << Q
    assert np.array_equal(scaled, scaled[::-1])
    return scaled


def chain_response(taps: np.ndarray, freqs: np.ndarray) -> np.ndarray:
    """|H| of RC x boxcar x FIR at ``freqs`` (Hz), relative to DC."""
    tau = 1.0 / (2 * np.pi * 243.0)
    rc = 1.0 / np.sqrt(1 + (2 * np.pi * freqs * tau) ** 2)
    x = np.pi * freqs * R1 / FS_ADC
    boxcar = np.abs(np.where(x == 0, 1.0, np.sin(x) / (R1 * np.sin(np.pi * freqs / FS_ADC))))
    _, fir = signal.freqz(taps / (1 << Q), worN=freqs, fs=FS_STAGE1)
    response: np.ndarray = rc * boxcar * np.abs(fir)
    return response


def group_delay_s() -> float:
    """Delay of the stamped output behind the signal it represents: half the
    boxcar plus half the FIR, both linear phase."""
    return (R1 - 1) / 2 / FS_ADC + (NUM_TAPS - 1) / 2 / FS_STAGE1


def report(taps: np.ndarray) -> str:
    lines = [
        f"FS_ADC {FS_ADC:.3f} Hz, stage 1 {FS_STAGE1:.3f} Hz, output {FS_OUT:.3f} Hz",
        f"group delay {group_delay_s() * 1e6:.0f} us",
    ]
    for f in (50, 100, 150, 180, 200, 252, 304, 400, 1000, 1711):
        db = 20 * np.log10(max(chain_response(taps, np.array([float(f)]))[0], 1e-12))
        lines.append(f"  {f:5d} Hz  {db:7.2f} dB")
    stop = np.linspace(STOP_HZ, FS_STAGE1 / 2, 2000)
    worst = 20 * np.log10(chain_response(taps, stop).max())
    lines.append(f"worst stopband ({STOP_HZ:.0f} Hz up): {worst:.1f} dB")
    return "\n".join(lines)


def render(taps: np.ndarray) -> str:
    body = ",\n".join(
        "    " + ", ".join(f"{int(t)}" for t in taps[i : i + 8]) for i in range(0, NUM_TAPS, 8)
    )
    return f"""/* Generated by design_fir.py -- do not edit; rerun it instead. */
#ifndef FIR_TAPS_H
#define FIR_TAPS_H

#define R1 {R1}u
#define R2 {R2}u
#define NUM_TAPS {NUM_TAPS}u
/* Output rate in mHz and group delay in us, announced on the #FW line. */
#define OUTPUT_MHZ {round(FS_OUT * 1000)}u
#define GROUP_DELAY_US {round(group_delay_s() * 1e6)}u

/* Q15, symmetric, summing to 32768 (unit DC gain). Pass 0-{PASS_HZ:.0f} Hz,
 * stop from {STOP_HZ:.0f} Hz at {FS_STAGE1:.1f} Hz. */
static const int16_t FIR_TAPS[NUM_TAPS] = {{
{body}
}};

#endif
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if fir_taps.h is stale")
    args = parser.parse_args()
    taps = design()
    text = render(taps)
    print(report(taps))
    if args.check:
        if HEADER.read_text() != text:
            print(f"{HEADER} is stale: rerun design_fir.py", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

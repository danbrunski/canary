# ruff: noqa: E501, N802, N806
"""Build canary-capbank.kicad_pcb from the schematic netlist (run with KiCad's python).

A fresh 2-layer board: outline, tie-down slots and mounting holes, every footprint from the netlist at its
layout.py position, then layout.py's pours, tracks and vias. Nothing here is hand-edited afterwards yet, so
regenerating is safe; once the board is edited in KiCad the board file becomes the source of truth.

Usage: gen_pcb.py <netlist.xml> <out.kicad_pcb> <project_dir_windows> <syslib_fp_dir>
"""

import os
import sys
import xml.etree.ElementTree as ET

import pcbnew

net_xml, out_path, projdir, sysfp = sys.argv[1:5]
MM = pcbnew.FromMM
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(1, os.path.join(HERE, "..", "..", "tools"))
import layout  # noqa: E402
import silk_refs  # noqa: E402


def V(x, y):
    return pcbnew.VECTOR2I(MM(x), MM(y))


b = pcbnew.BOARD()
b.SetCopperLayerCount(2)
ds = b.GetDesignSettings()
ds.SetBoardThickness(MM(1.6))
tb = b.GetTitleBlock()
tb.SetTitle("CANary cap bank")
tb.SetRevision("1.0")
tb.SetDate("2026-10-20")
tb.SetCompany("CANary")
tb.SetComment(
    0, "Four 25 F cells for CANary-PWR's LTC3350. Design record: docs/CANary-PWR-Spec.md P4"
)
tb.SetComment(1, "2 layers, 1.6 mm, 1 oz. Generated by gen/gen_pcb.py from gen/layout.py")


def shape(kind, layer, pts, width=0.1):
    s = pcbnew.PCB_SHAPE(b)
    s.SetShape(kind)
    s.SetLayer(layer)
    s.SetWidth(MM(width))
    if kind == pcbnew.SHAPE_T_ARC:
        s.SetArcGeometry(V(*pts[0]), V(*pts[1]), V(*pts[2]))
    else:
        s.SetStart(V(*pts[0]))
        s.SetEnd(V(*pts[1]))
    b.Add(s)


def rounded_rect(layer, x0, y0, x1, y1, r, width=0.1):
    """A closed outline with corner radius r (r = half the short side makes a slot)."""
    k = r * (1 - 0.70710678)
    for a, c in (
        ((x0 + r, y0), (x1 - r, y0)),
        ((x1, y0 + r), (x1, y1 - r)),
        ((x1 - r, y1), (x0 + r, y1)),
        ((x0, y1 - r), (x0, y0 + r)),
    ):
        if a != c:
            shape(pcbnew.SHAPE_T_SEGMENT, layer, (a, c), width)
    for start, mid, end in (
        ((x1 - r, y0), (x1 - k, y0 + k), (x1, y0 + r)),
        ((x1, y1 - r), (x1 - k, y1 - k), (x1 - r, y1)),
        ((x0 + r, y1), (x0 + k, y1 - k), (x0, y1 - r)),
        ((x0, y0 + r), (x0 + k, y0 + k), (x0 + r, y0)),
    ):
        shape(pcbnew.SHAPE_T_ARC, layer, (start, mid, end), width)


# ---------------------------------------------------------------- outline, slots, text
rounded_rect(pcbnew.Edge_Cuts, *layout.BOARD, layout.CORNER_R)
for x0, y0, x1, y1 in layout.SLOTS:  # cable-tie slots: internal cut-outs
    rounded_rect(pcbnew.Edge_Cuts, x0, y0, x1, y1, min(x1 - x0, y1 - y0) / 2)
for txt, x, y, layer, size in layout.TEXT:
    t = pcbnew.PCB_TEXT(b)
    t.SetText(txt)
    t.SetPosition(V(x, y))
    t.SetLayer({"F": pcbnew.F_SilkS, "B": pcbnew.B_SilkS}[layer])
    t.SetTextSize(V(size, size))
    t.SetTextThickness(MM(max(0.15, size * 0.15)))
    if layer == "B":
        t.SetMirrored(True)
    b.Add(t)
for layer, kind, pts, width in layout.SILK:
    shape(
        {"segment": pcbnew.SHAPE_T_SEGMENT}[kind],
        {"F": pcbnew.F_SilkS, "B": pcbnew.B_SilkS}[layer],
        pts,
        width,
    )

# ---------------------------------------------------------------- netlist
root = ET.parse(net_xml).getroot()
pad_net, nets = {}, {}
for n in root.iter("net"):
    for node in n.iter("node"):
        pad_net[(node.get("ref"), node.get("pin"))] = n.get("name")
    nets[n.get("name")] = None
for name in sorted(nets):
    ni = pcbnew.NETINFO_ITEM(b, name)
    b.Add(ni)
    nets[name] = ni


def load_fp(fpid):
    lib, name = fpid.split(":", 1)
    path = (
        os.path.join(projdir, "lib", "footprints.pretty")
        if lib == "canary-capbank"
        else os.path.join(sysfp, lib + ".pretty")
    )
    fp = pcbnew.FootprintLoad(path, name)
    if fp is None:
        raise SystemExit(f"cannot load {fpid} from {path}")
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    # A stock model that KiCad's 3D library lacks (the Micro-Fit headers) comes from the project's own
    # lib/3dmodels, written by hardware/tools/gen_3dmodels.py under the same file name.
    for i in range(len(fp.Models())):
        m = fp.Models()[i]  # by index: iterating the vector yields copies
        base = m.m_Filename.rsplit("/", 1)[-1]
        if os.path.exists(os.path.join(projdir, "lib", "3dmodels", base)):
            m.m_Filename = "${KIPRJMOD}/lib/3dmodels/" + base
    return fp


def put(fp, x, y, rot, side):
    b.Add(fp)  # the board must own it before a flip, to mirror the layers
    if side == "B":
        fp.Flip(fp.GetPosition(), pcbnew.FLIP_DIRECTION_TOP_BOTTOM)
    fp.SetOrientationDegrees(rot)
    fp.SetPosition(V(x, y))


for c in root.iter("comp"):
    ref = c.get("ref")
    fp = load_fp(c.find("footprint").text)
    fp.SetReference(ref)
    fp.SetValue(c.find("value").text)
    fp.SetPath(pcbnew.KIID_PATH(c.find("sheetpath").get("tstamps") + c.find("tstamps").text))
    for f in c.iter("field"):
        if f.get("name") != "Footprint":
            fp.SetField(f.get("name"), f.text or "")
            fp.GetField(f.get("name")).SetVisible(False)
    for pad in fp.Pads():
        net = pad_net.get((ref, pad.GetNumber()))
        if net:
            pad.SetNet(nets[net])
    if ref not in layout.PLACEMENT:
        raise SystemExit(f"{ref} has no position in layout.py")
    put(fp, *layout.PLACEMENT[ref])

for i, (x, y) in enumerate(layout.HOLES, 1):
    fp = load_fp("MountingHole:MountingHole_3.2mm_M3")
    fp.SetReference(f"MH{i}")
    fp.SetBoardOnly(True)  # no schematic symbol
    fp.Value().SetVisible(False)
    put(fp, x, y, 0, "F")

print(f"silk references: {silk_refs.place_refs(b)}")


# ---------------------------------------------------------------- copper
SIDE = {"F": pcbnew.F_Cu, "B": pcbnew.B_Cu}


def zone(layer, net, pts, prio, connect):
    z = pcbnew.ZONE(b)
    z.SetLayer(layer)
    o = z.Outline()
    o.NewOutline()
    for px, py in pts:
        o.Append(MM(px), MM(py))
    z.SetNet(nets[net])
    z.SetLocalClearance(MM(0.3))
    z.SetMinThickness(MM(0.25))
    z.SetAssignedPriority(prio)
    z.SetPadConnection(connect)
    z.SetThermalReliefSpokeWidth(
        MM(0.8)
    )  # 4 spokes x 2 layers carry 7 A into a lead and still solder by hand
    z.SetThermalReliefGap(MM(0.4))
    b.Add(z)


for name, side, pts, prio in layout.POURS:
    zone(SIDE[side], name, pts, prio, pcbnew.ZONE_CONNECTION_THERMAL)
for side, pts in layout.KEEPOUTS:  # rule areas that keep the pours off the Kelvin joins
    k = pcbnew.ZONE(b)
    k.SetIsRuleArea(True)
    k.SetLayer(SIDE[side])
    o = k.Outline()
    o.NewOutline()
    for px, py in pts:
        o.Append(MM(px), MM(py))
    k.SetDoNotAllowZoneFills(True)
    for allow in (
        k.SetDoNotAllowTracks,
        k.SetDoNotAllowVias,
        k.SetDoNotAllowPads,
        k.SetDoNotAllowFootprints,
    ):
        allow(False)
    b.Add(k)
for name, side, width, pts in layout.TRACKS:
    for (xa, ya), (xb, yb) in zip(pts, pts[1:], strict=False):
        t = pcbnew.PCB_TRACK(b)
        t.SetStart(V(xa, ya))
        t.SetEnd(V(xb, yb))
        t.SetWidth(MM(width))
        t.SetLayer(SIDE[side])
        t.SetNet(nets[name])
        b.Add(t)
for name, x, y, dia, drill in layout.VIAS:
    v = pcbnew.PCB_VIA(b)
    b.Add(v)
    v.SetViaType(pcbnew.VIATYPE_THROUGH)
    v.SetLayerPair(pcbnew.F_Cu, pcbnew.B_Cu)
    v.SetPosition(V(x, y))
    v.SetWidth(MM(dia))
    v.SetDrill(MM(drill))
    v.SetNet(nets[name])
pcbnew.ZONE_FILLER(b).Fill(b.Zones())
pcbnew.SaveBoard(out_path, b, True)  # True: leave the .kicad_pro alone
print(
    f"{len(list(b.GetFootprints()))} footprints, {len(layout.POURS)} pours, {sum(len(p) - 1 for *_, p in layout.TRACKS)} track segments, {len(layout.VIAS)} vias"
)

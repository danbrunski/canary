#!/usr/bin/env python3
"""Write tests/slow_tests.txt from a pytest ``--durations`` report.

    pytest -m "not integration and not ml_training" --durations=0 --durations-min=2 > d.log
    scripts/mark_slow_tests.py d.log [--threshold 1.5]

A test whose setup + call + teardown took at least ``--threshold`` seconds is
listed; ``tests/conftest.py`` marks every listed test ``slow``, which the
one-minute push gate (scripts/ci_gate.sh) skips and GitHub CI still runs.
Re-run it when the gate creeps past a minute or a slow test gets faster.

Measure on a quiet machine with few workers (``-n 4``): under ``-n auto`` with
the slow tier running alongside, ordinary tests read 2-4x their own time
(2026-10-17: 881 listed at -n 12, 433 at -n 4). Every node id passed must
still exist -- one stale id makes pytest run nothing at all.
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LINE = re.compile(r"^\s*([\d.]+)s (setup|call|teardown)\s+(\S+)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("report", type=Path)
    parser.add_argument("--threshold", type=float, default=1.5)
    args = parser.parse_args()
    seconds: dict[str, float] = defaultdict(float)
    for line in args.report.read_text().splitlines():
        if match := LINE.match(line):
            seconds[match.group(3)] += float(match.group(1))
    slow = sorted((node, s) for node, s in seconds.items() if s >= args.threshold)
    out = REPO / "tests" / "slow_tests.txt"
    header = [
        "# Tests slower than the push gate can afford; tests/conftest.py marks them",
        "# `slow`. Generated by scripts/mark_slow_tests.py -- do not edit by hand.",
        f"# Measured {date.today().isoformat()}: setup+call+teardown >= {args.threshold} s, "
        "seconds after each id.",
    ]
    out.write_text("\n".join([*header, *(f"{node} {s:.1f}" for node, s in slow)]) + "\n")
    print(f"wrote {out.relative_to(REPO)}: {len(slow)} tests, {sum(s for _, s in slow):.0f} s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

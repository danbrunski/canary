#!/usr/bin/env bash
set -euo pipefail

# Strip one Pi's identity from an installed CANary so its SD card can be
# imaged and handed to someone else (docs/roadmap/archive/phone-ui.md P2.4).
#
#   sudo scripts/prepare_image.sh        # then power off and image the card
#
# Run on the reference Pi after scripts/install_pi.sh. Everything removed here
# is something every copy of the image would otherwise share. The first boot
# of each copy regenerates it (scripts/canary_firstboot.sh, run once by
# canary-firstboot.service):
#
# - the shared control token: anyone with one copy could control every other;
# - paired devices: the builder's phone must not control a customer's Pi;
# - WiFi client profiles, so the copy boots unprovisioned and BLE setup is
#   open (src/provisioning/gate.py);
# - the hostname (canary-XXXX comes from each Pi's own MAC), machine-id and
#   SSH host keys.
#
# CANARY_INSTALL_ROOT is a test hook (tests/test_prepare_image.py), as in
# install_pi.sh.

if [[ "${EUID}" -ne 0 && "${CANARY_INSTALL_ALLOW_UNPRIVILEGED:-0}" != "1" ]]; then
  echo "Run with sudo: sudo scripts/prepare_image.sh" >&2
  exit 1
fi

ROOT="${CANARY_INSTALL_ROOT:-}"
CONFIG_DIR="${ROOT}/etc/canary"
ENV_FILE="${CONFIG_DIR}/canary.env"
MARKER="${CONFIG_DIR}/firstboot"

if [[ ! -f "${ENV_FILE}" ]]; then
  echo "No ${ENV_FILE}: run scripts/install_pi.sh first." >&2
  exit 1
fi

data_dir="$(sed -n 's/^CANARY_DATA_DIR=//p' "${ENV_FILE}")"

rm -f "${CONFIG_DIR}/control.token"
sed -i 's/^CANARY_CONTROL_TOKEN=.*/CANARY_CONTROL_TOKEN=/' "${ENV_FILE}"
echo "removed the control token"

if [[ -n "${data_dir}" ]]; then
  rm -f "${ROOT}${data_dir}/control/paired_devices.json" \
    "${ROOT}${data_dir}/control/paired_devices.json.bak"
  echo "removed paired devices"
fi

# WiFi client profiles only: an access-point profile (mode=ap) is the image's
# own, not the builder's network.
nm_dir="${ROOT}/etc/NetworkManager/system-connections"
if [[ -d "${nm_dir}" ]]; then
  for profile in "${nm_dir}"/*.nmconnection; do
    [[ -e "${profile}" ]] || continue
    grep -qE '^type=(wifi|802-11-wireless)$' "${profile}" || continue
    grep -q '^mode=ap$' "${profile}" && continue
    rm -f "${profile}"
    echo "removed WiFi profile $(basename "${profile}")"
  done
fi

printf 'canary\n' >"${ROOT}/etc/hostname"
if [[ -f "${ROOT}/etc/hosts" ]]; then
  sed -i 's/^127\.0\.1\.1[[:space:]].*/127.0.1.1\tcanary/' "${ROOT}/etc/hosts"
fi
# An empty machine-id is regenerated by systemd at boot.
if [[ -f "${ROOT}/etc/machine-id" ]]; then
  : >"${ROOT}/etc/machine-id"
fi
rm -f "${ROOT}"/etc/ssh/ssh_host_*

touch "${MARKER}"
echo "Ready to image. Power off now; the next boot of any copy runs canary-firstboot."

#!/usr/bin/env bash
# Regenerate constraints-dev.txt from the laptop venv: the exact versions CI and
# every local gate install. CI (.github/workflows/ci.yml) installs with
# `-c constraints-dev.txt`, and scripts/check.sh refuses to run when the venv has
# drifted from it, so "green locally" means "green in CI".
#
# Why a lock and not per-package pins: CI used to install the newest release of
# everything. On 2026-09-19 a pandas-stubs release, and on 2026-09-23 mypy 2.x
# with numpy 2.5 stubs, changed the type-check verdict on code nobody touched,
# while the laptop, on older versions, stayed green. Pinning one package after
# each failure only moves the drift to the next one.
#
# To upgrade deliberately:
#   .venv/bin/pip install -U <pkg>        # or -U -e '.[dev]'
#   scripts/check.sh --no-env-check       # the whole gate, green, on the new versions
#   scripts/lock_dev_constraints.sh       # re-lock, then commit the diff with the fix
#
# CUDA/torch wheels are excluded: CI does not install the `ml` extra, and the
# local torch build comes from scripts/install_deps.py to match the driver.
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
out=constraints-dev.txt
{
  echo "# Generated by scripts/lock_dev_constraints.sh -- do not edit by hand."
  echo "# The exact dev toolchain CI and scripts/check.sh use. See that script to upgrade."
  .venv/bin/pip freeze --exclude-editable --disable-pip-version-check \
    | grep -viE '^(torch|triton|nvidia-|cuda-)' \
    | grep -v '+' \
    | LC_ALL=C sort -f
} > "$out"
echo "wrote $out ($(grep -vc '^#' "$out") packages)"

#!/usr/bin/env python3
"""Generate (or check) the known-answer investigation case expectations (E01.6).

Replays every case in ``tests/fixtures/ground_truth/investigation_cases.yaml``
through the real chain (``src.analysis.known_cases``: compare_channels ->
MemoryLedger -> investigation_card) and writes what it says to
``investigation_cases.expected.yaml``. The hand-written ``known`` checks are
the labels; this file is the tool's own account, so a change in what the
chain says is a reviewed diff instead of a silent drift. A case whose known
checks fail is refused: the snapshot is never regenerated over a wrong answer.

``--verify-sources <sessions root>`` re-counts each drive's ``full_session``
facts (chunks, first/last sample, Mode 01 rows, per-channel rows, capture
profile) from the operator's local pull, which is what lets the case file say
a channel was never captured rather than merely absent from a slice. Laptop
only: it reads whole sessions (AGENTS.md, "No analysis on the Pi while it
collects").

Usage:
  .venv/bin/python tools/make_investigation_cases.py            # check only
  .venv/bin/python tools/make_investigation_cases.py --write
  .venv/bin/python tools/make_investigation_cases.py \\
      --verify-sources ~/canary-data/sessions/nissan-xterra-2008
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from collections.abc import Sequence
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURE_ROOT = REPO_ROOT / "tests" / "fixtures" / "ground_truth"
CASES = FIXTURE_ROOT / "investigation_cases.yaml"
EXPECTED = FIXTURE_ROOT / "investigation_cases.expected.yaml"

HEADER = """\
# GENERATED by tools/make_investigation_cases.py --write — do not edit by hand.
#
# What the real chain (compare_channels -> MemoryLedger -> investigation_card)
# says for every case in investigation_cases.yaml, record ids replaced by the
# case's step names. The known answers live in that file; this is the tool's
# account, checked by tests/test_investigation_cases.py so any drift is a
# reviewed diff. Numbers are rounded to six significant figures.
"""


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="make_investigation_cases",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--write", action="store_true", help=f"Rewrite {EXPECTED.name}.")
    parser.add_argument(
        "--verify-sources",
        type=Path,
        default=None,
        help="Sessions root holding the drives' full sessions; re-count full_session facts.",
    )
    return parser.parse_args(argv)


def generate(scratch: Path) -> tuple[dict[str, Any], list[str]]:
    from src.analysis.known_cases import (
        EXPECTED_SCHEMA,
        SliceAbsenceError,
        case_outcome,
        check_case,
        load_case_file,
        run_case,
        run_negative_control,
    )

    cases = load_case_file(CASES)
    problems: list[str] = []
    outcomes: dict[str, Any] = {}
    for case_id, case in cases.cases.items():
        run = run_case(cases, case_id, workdir=scratch / case_id, fixture_root=FIXTURE_ROOT)
        outcome = case_outcome(run)
        report = check_case(case, outcome)
        problems.extend(f"{case_id}: known answer failed: {line}" for line in report.failures)
        problems.extend(
            f"{case_id}: known defect now passes (promote the check): {line}"
            for line in report.defects_passing
        )
        outcomes[case_id] = outcome
    controls: dict[str, Any] = {}
    for control_id, control in cases.negative_controls.items():
        workdir = scratch / f"control-{control_id}"
        try:
            report = run_negative_control(
                cases, control_id, workdir=workdir, fixture_root=FIXTURE_ROOT
            )
        except SliceAbsenceError as refusal:
            controls[control_id] = {"raises": type(refusal).__name__}
            if control.raises != type(refusal).__name__:
                problems.append(f"{control_id}: unexpected refusal: {refusal}")
            continue
        failed = sorted({line.split(" ", 1)[0] for line in report.failures})
        controls[control_id] = {"failures": failed}
        missed = [path for path in control.must_fail if path not in failed]
        if control.raises is not None or missed:
            problems.append(f"{control_id}: negative control did not fail as named: {missed}")
    return {"schema": EXPECTED_SCHEMA, "cases": outcomes, "negative_controls": controls}, problems


def _count(session: Path, specs: list[str]) -> dict[str, Any]:
    import duckdb

    pattern = str(session / "telemetry-*.parquet")
    con = duckdb.connect()
    summary = con.execute(
        f"""
        SELECT min(timestamp), max(timestamp),
               count(*) FILTER (WHERE source = 'obd' AND channel NOT LIKE 'DID_%'
                                AND channel NOT LIKE 'mem:%')
        FROM read_parquet('{pattern}')
        """
    ).fetchone()
    assert summary is not None
    first, last, mode01 = summary
    rows = {}
    for spec in specs:
        namespace, name = spec.split(":", 1)
        channel = spec if namespace == "mem" else name
        source = "obd" if namespace in ("obd", "mem") else namespace
        found = con.execute(
            f"SELECT count(*) FROM read_parquet('{pattern}') WHERE source = ? AND channel = ?",
            [source, channel],
        ).fetchone()
        rows[spec] = 0 if found is None else int(found[0])
    return {"first": first, "last": last, "mode01_rows": int(mode01), "channel_rows": rows}


def verify_sources(root: Path) -> list[str]:
    import pandas as pd

    from src.analysis.known_cases import load_case_file

    cases = load_case_file(CASES)
    problems: list[str] = []
    for drive_id, drive in cases.drives.items():
        session = root.expanduser() / drive.session
        if not session.is_dir():
            print(f"{drive_id}: {session} not in this pull; skipped")
            continue
        facts = drive.full_session
        counted = _count(session, sorted(facts.channel_rows))
        chunks = len(list(session.glob("telemetry-*.parquet")))
        manifest = session / "capture_profile.json"
        profile = mode01 = None
        if manifest.exists():
            data = json.loads(manifest.read_text())
            profile = data.get("profile")
            mode01 = data.get("profile_snapshot", {}).get("mode01_enabled")
        observed: dict[str, Any] = {
            "chunks": chunks,
            "first_sample": pd.Timestamp(counted["first"]),
            "last_sample": pd.Timestamp(counted["last"]),
            "capture_profile": profile,
            "mode01_enabled": mode01,
            "mode01_rows": counted["mode01_rows"],
            "channel_rows": counted["channel_rows"],
        }
        stated: dict[str, Any] = {
            "chunks": facts.chunks,
            "first_sample": pd.Timestamp(facts.first_sample),
            "last_sample": pd.Timestamp(facts.last_sample),
            "capture_profile": facts.capture_profile,
            "mode01_enabled": facts.mode01_enabled,
            "mode01_rows": facts.mode01_rows,
            "channel_rows": dict(facts.channel_rows),
        }
        for key, value in stated.items():
            if observed[key] != value:
                problems.append(
                    f"{drive_id}.{key}: file says {value!r}, session has {observed[key]!r}"
                )
        print(f"{drive_id}: checked {chunks} chunks of {drive.session}")
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    sys.path.insert(0, str(REPO_ROOT))
    import yaml

    if args.verify_sources is not None:
        problems = verify_sources(args.verify_sources)
        for line in problems:
            print(f"MISMATCH {line}", file=sys.stderr)
        return 1 if problems else 0
    with tempfile.TemporaryDirectory(prefix="investigation-cases-") as scratch:
        generated, problems = generate(Path(scratch))
    for line in problems:
        print(f"REFUSED {line}", file=sys.stderr)
    if problems:
        return 1
    text = HEADER + yaml.safe_dump(generated, sort_keys=False, allow_unicode=True, width=100)
    if args.write:
        EXPECTED.write_text(text)
        print(f"wrote {EXPECTED.relative_to(REPO_ROOT)}")
        return 0
    current = EXPECTED.read_text() if EXPECTED.exists() else ""
    if yaml.safe_load(current or "{}") != yaml.safe_load(text):
        print(f"{EXPECTED.name} differs from what the chain says now; rerun with --write")
        return 1
    print(f"{EXPECTED.name} matches the chain")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
